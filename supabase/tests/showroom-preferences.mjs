import assert from 'node:assert/strict';
import {emptyFilters,preferenceKey,readPreferences,savePreferences,sortedCars} from '../../showroom-preferences.mjs';
const rows=[{id:'a',price:27990,year:2017},{id:'b',price:12990,year:2011},{id:'c',price:89990,year:2019},{id:'d',price:null,year:null}];
assert.deepEqual(sortedCars(rows,'price-low').map(c=>c.id),['b','a','c','d']);
assert.deepEqual(sortedCars(rows,'price-high').map(c=>c.id),['c','a','b','d']);
assert.deepEqual(sortedCars(rows,'year-new').map(c=>c.id),['c','a','b','d']);
assert.deepEqual(rows.map(c=>c.id),['a','b','c','d']);
assert.deepEqual(sortedCars(rows,'latest'),rows);
const values=new Map(),storage={getItem:k=>values.get(k),setItem:(k,v)=>values.set(k,v)};
savePreferences(storage,{...emptyFilters,q:'CR-V',brand:'Honda',yearFrom:'2017'},'price-low');
assert.equal(readPreferences(storage).filters.q,'CR-V');
assert.equal(readPreferences(storage).filters.brand,'Honda');
assert.equal(readPreferences(storage).sort,'price-low');
assert.equal(readPreferences(storage,Date.now()+5*60*60*1000).filters.q,'');
storage.setItem(preferenceKey,'invalid json');assert.equal(readPreferences(storage).sort,'latest');
assert.deepEqual(readPreferences(undefined).filters,emptyFilters);
assert.doesNotThrow(()=>savePreferences(undefined,emptyFilters,'latest'));
storage.setItem(preferenceKey,JSON.stringify({savedAt:Date.now(),filters:{q:{html:'bad'},brand:'x'.repeat(121)},sort:'invalid'}));
assert.equal(readPreferences(storage).filters.q,'');assert.equal(readPreferences(storage).filters.brand,'');assert.equal(readPreferences(storage).sort,'latest');
console.log('Showroom sorting and saved-filter checks passed.');
